/* Длины фаз — в долях экрана, все в одном месте. Держим их вместе, потому что
   они связаны: пауза «атмосферы» должна совпадать по длине с уездом
   «направлений», а подкладка следующей секции считается от той же длины.
   Разъедутся — на стыке мелькнёт полоса фона.

   Это же и ручка темпа всей страницы: закреплённые сцены съедают больше
   половины прокрутки, и если сайт кажется тягучим — крутить нужно здесь,
   а не в отдельных модулях. */

export const screen = () => window.innerHeight;

/* Уезд секции влево, открывающий следующую. */
export const exitLength = () => screen() * 0.7;

/* Растворение секции на месте, открывающее подложенную под неё. */
export const dissolveLength = () => screen() * 0.6;

/* Раскрытие жалюзи. */
export const openLength = () => screen() * 0.6;

/* Сколько прокрутки тратится на пиксель хода ленты. Меньше единицы — лента
   едет быстрее пальца; при 1.0 семь карточек стоили бы почти четыре экрана. */
export const RAIL_PACE = 0.7;

/* Один шаг стопки: сколько прокрутки стоит въезд следующей карточки
   (и оседание предыдущей — они идут одновременно). */
export const stackStep = () => screen() * 0.5;
