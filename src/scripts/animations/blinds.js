/* Жалюзи: полосы цвета предыдущего блока расходятся и открывают то, что под
   ними. Полосы прибиты и к верху, и к низу блока — зазоры появляются только
   между ними. Отсюда формула: полоса сжимается по scaleY и дополнительно
   съезжает вниз на четверть своей высоты, помноженную на её номер.

   Механизм общий: им открываются и направления, и футер. Здесь только
   параметры твина, чтобы обе сцены считали раскрытие одинаково. */
export function blindsOpen(duration) {
  return {
    scaleY: 0,
    yPercent: (index) => index * 25,
    duration
  };
}
